"""Generate the offline parse drafts and the review packet for the licensed corpus.

The packet that earlier sessions reviewed was produced by throwaway scripts, so a
new parser version could not be re-reviewed reproducibly. This tool is the durable
replacement: it parses every licensed local PDF with the current parser, writes one
draft JSON per paper, and emits a compact review packet over a fixed sample list.

It is read-only with respect to the database: it never opens or writes SQLite.

Usage (from ``backend/``)::

    uv run --locked python -m tools.generate_parse_review --parser-version v27
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from app.retrieval.pdf_parser import PARSER_VERSION, parse_pdf

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT_DIR = REPO_ROOT / "backend" / "reports" / "live_eval"
DEFAULT_PAGE_DIR = REPO_ROOT / "backend" / "reports" / "live_eval" / "v23-review-pages"

# Local file names for the nine CC BY 4.0 papers currently approved for full text.
SOURCE_PDFS: dict[str, str] = {
    "2607.24663": "A corrective agentic hybrid RAG.pdf",
    "2608.02037": "A  Heterogeneous 200 mm Silicon.pdf",
    "2608.20519": "An integrated diffusion-weighted.pdf",
    "2609.27579": "integration of RAG.pdf",
    "2609.39773": "riemannian flow models with.pdf",
    "2610.06874": "statistical turbulence and.pdf",
    "2610.09789": "cooperation, Defection, and the commons.pdf",
    "2610.10204": "Three-dimensional Largrangian.pdf",
    "2610.12662": "evaluating llms for translating.pdf",
}

# Fixed sample list: every element of the expected type on that page is reviewed.
SAMPLES: list[tuple[str, int, str]] = [
    ("2610.09789", 5, "table"),
    ("2610.09789", 9, "figure_caption"),
    ("2610.09789", 10, "table"),
    ("2610.09789", 6, "figure_caption"),
    ("2610.12662", 14, "table"),
    ("2610.12662", 16, "table"),
    ("2610.12662", 17, "table"),
    ("2610.12662", 15, "figure_caption"),
    ("2609.39773", 35, "table"),
    ("2609.39773", 39, "table"),
    ("2610.06874", 14, "table"),
    ("2610.06874", 21, "table"),
    ("2610.06874", 13, "figure_caption"),
    ("2610.10204", 3, "figure_caption"),
    ("2610.10204", 4, "figure_caption"),
    ("2610.10204", 5, "figure_caption"),
]


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def _render_element(element: dict) -> list[str]:
    lines = [
        f"#### Parsed element · `{element['element_id']}`",
        "",
        f"bbox: `{element['bbox']}`",
        "",
        f"warnings: `{json.dumps(element['warnings'], ensure_ascii=False)}`",
        "",
    ]
    structured = element.get("structured") or {}
    if structured:
        meta = {key: value for key, value in structured.items() if key not in {"rows", "header"}}
        lines.extend([f"structure: `{json.dumps(meta, ensure_ascii=False)}`", ""])
        rows = structured.get("rows") or []
        if rows:
            lines.extend(["```text", *render_rows(rows), "```", ""])
        relation = structured.get("image_relation")
        if relation:
            lines.extend([f"image_relation: `{json.dumps(relation, ensure_ascii=False)}`", ""])
    else:
        lines.extend(["```text", (element.get("text") or "").strip()[:1200], "```", ""])
    return lines


def render_rows(rows: list[dict]) -> list[str]:
    """One pipe-joined line per parsed row, matching the draft row indexes."""
    rendered = []
    for row in rows:
        cells = [str(cell.get("text", "")).replace("\n", " ") for cell in row.get("cells", [])]
        rendered.append(f"row_index={row.get('row_index')}: " + " | ".join(cells))
    return rendered


def build_packet(
    drafts: dict[str, dict], page_dir: Path, *, parser_version: str
) -> tuple[str, dict[str, object]]:
    sections: list[str] = [
        f"# Parse review packet ({PARSER_VERSION})",
        "",
        "Generated by `backend/tools/generate_parse_review.py`. Review every sample against the",
        "original PDF page image: element type, text completeness, table row/column mapping, and",
        f"caption-to-figure relation. Parser version: `{parser_version}`.",
        "",
        "## Sources",
        "",
    ]
    manifest: dict[str, object] = {"parser_version": parser_version, "samples": []}
    for arxiv_id in sorted(drafts):
        draft = drafts[arxiv_id]
        sections.append(
            f"- `{arxiv_id}`: {draft['page_count']} pages, "
            f"{len(draft['elements'])} elements, {len(draft['warnings'])} page warnings"
        )
    sections.append("")
    sections.append("## Samples")
    sections.append("")

    for index, (arxiv_id, page_number, element_type) in enumerate(SAMPLES, start=1):
        if arxiv_id not in drafts:
            continue
        draft = drafts[arxiv_id]
        elements = [
            element
            for element in draft["elements"]
            if element["page_number"] == page_number and element["element_type"] == element_type
        ]
        sample_id = f"{arxiv_id}-S{index}"
        sections.extend(
            [
                f"### {sample_id} · PDF page {page_number} · expected `{element_type}`",
                "",
                f"Original page: [{arxiv_id} page {page_number}]"
                f"({page_dir.name}/{arxiv_id}-p{page_number}.png)",
                "",
            ]
        )
        if not elements:
            sections.extend(["**No parsed element of this type on this page.**", ""])
        for element in elements:
            sections.extend(_render_element(element))
        manifest["samples"].append(
            {
                "sample_id": sample_id,
                "arxiv_id": arxiv_id,
                "page": page_number,
                "expected_type": element_type,
                "element_ids": [element["element_id"] for element in elements],
                "element_count": len(elements),
            }
        )
    return "\n".join(sections).rstrip() + "\n", manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--parser-version", default=PARSER_VERSION)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--page-dir", type=Path, default=DEFAULT_PAGE_DIR)
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT)
    parser.add_argument("--only", default="", help="comma-separated arXiv ids to parse")
    args = parser.parse_args()

    wanted = {value.strip() for value in args.only.split(",") if value.strip()}
    args.output_dir.mkdir(parents=True, exist_ok=True)
    drafts: dict[str, dict] = {}
    for arxiv_id, file_name in sorted(SOURCE_PDFS.items()):
        if wanted and arxiv_id not in wanted:
            continue
        pdf_path = args.repo_root / file_name
        if not pdf_path.exists():
            raise SystemExit(f"missing licensed PDF for {arxiv_id}: {pdf_path}")
        draft = parse_pdf(pdf_path)
        drafts[arxiv_id] = draft
        target = args.output_dir / f"{arxiv_id}-{args.parser_version}-draft.json"
        target.write_text(json.dumps(draft, ensure_ascii=False), encoding="utf-8")
        print(
            f"{arxiv_id}: {draft['page_count']} pages, "
            f"{len(draft['elements'])} elements -> {target.name}"
        )

    packet, manifest = build_packet(drafts, args.page_dir, parser_version=args.parser_version)
    packet_path = args.output_dir / f"corpus-expansion-{args.parser_version}-review.md"
    packet_path.write_text(packet, encoding="utf-8")
    manifest["packet_sha256"] = hashlib.sha256(packet.encode("utf-8")).hexdigest()
    manifest["pdf_sha256"] = {
        arxiv_id: _sha256(args.repo_root / file_name)
        for arxiv_id, file_name in sorted(SOURCE_PDFS.items())
    }
    manifest_path = args.output_dir / f"R02-{args.parser_version}-review-manifest.json"
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"packet: {packet_path}")
    print(f"packet sha256: {manifest['packet_sha256']}")
    print(f"manifest: {manifest_path}")


if __name__ == "__main__":
    main()
